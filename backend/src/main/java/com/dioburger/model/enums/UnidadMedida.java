package com.dioburger.model.enums;

/**
 * Enum que representa las unidades de medida para ingredientes.
 * Cada unidad corresponde a una forma específica de medición.
 * 
 * @author Dio Burger Team
 * @version 1.0.0
 */
public enum UnidadMedida {
    /**
     * Medición por unidad completa (ej: 1 unidad de pan).
     */
    UNIDAD,
    
    /**
     * Medición por feta/rebanada (ej: 2 fetas de queso).
     */
    FETA,
    
    /**
     * Medición por hoja (ej: 3 hojas de lechuga).
     */
    HOJA,
    
    /**
     * Medición por rodaja (ej: 4 rodajas de tomate).
     */
    RODAJA,
    
    /**
     * Medición por porción (ej: 1 porción de carne).
     */
    PORCION,
    
    /**
     * Medición por puñado (ej: 1 puñado de cebolla).
     */
    PUNADO
}
